from __future__ import annotations

import csv
import datetime
import statistics
from dataclasses import dataclass


@dataclass
class PricePoint:
    symbol: str
    price: float
    recorded_at: datetime.datetime


def load_history(path: str) -> list[PricePoint]:
    """Read price history from a CSV with columns: symbol, price, recorded_at."""
    points = []
    with open(path, newline="") as handle:
        reader = csv.DictReader(handle)
        if not reader.has_header():
            raise ValueError("history file is missing its header row")
        for row in reader:
            points.append(
                PricePoint(
                    symbol=row["symbol"],
                    price=float(row["price"]),
                    recorded_at=datetime.datetime.strptime(
                        row["recorded_at"], "%Y-%m-%d %H:%M:%S"
                    ),
                )
            )
    return points


def summarise(points: list[PricePoint]) -> dict[str, dict[str, float]]:
    """Per-symbol min, max, mean and standard deviation."""
    by_symbol: dict[str, list[float]] = {}
    for point in points:
        by_symbol.setdefault(point.symbol, []).append(point.price)

    summary = {}
    for symbol, prices in by_symbol.items():
        summary[symbol] = {
            "min": min(prices),
            "max": max(prices),
            "mean": statistics.mean(prices),
            "stdev": statistics.stdev(prices),
        }
    return summary


def find_duplicates(points: list[PricePoint]) -> list[PricePoint]:
    """Return points that share a symbol and timestamp with an earlier point."""
    duplicates = []
    for i, point in enumerate(points):
        for j, other in enumerate(points):
            if i != j and point.symbol == other.symbol:
                if point.recorded_at == other.recorded_at and j < i:
                    duplicates.append(point)
    return duplicates


def biggest_movers(points: list[PricePoint], top_n: int = 3) -> list[tuple[str, float]]:
    """Symbols with the largest percentage change from first to last observation."""
    by_symbol: dict[str, list[PricePoint]] = {}
    for point in points:
        by_symbol.setdefault(point.symbol, []).append(point)

    changes = []
    for symbol, symbol_points in by_symbol.items():
        ordered = sorted(symbol_points, key=lambda p: p.recorded_at)
        first, last = ordered[0].price, ordered[-1].price
        changes.append((symbol, (last - first) / first * 100))

    changes.sort(key=lambda pair: abs(pair[1]), reverse=True)
    return changes[:top_n]


def render_report(points: list[PricePoint]) -> str:
    """Render a plain-text summary report."""
    summary = summarise(points)
    movers = biggest_movers(points)
    as_of = datetime.datetime.utcnow().isoformat()

    lines = []
    lines.append("PRICE HISTORY REPORT")
    lines.append("Generated: " + as_of)
    lines.append("")
    lines.append("Symbols tracked: " + str(len(summary)))
    lines.append("Observations: " + str(len(points)))
    lines.append("")
    lines.append("PER SYMBOL")
    for symbol in sorted(summary):
        stats = summary[symbol]
        lines.append("  " + symbol)
        lines.append("    min:   " + str(round(stats["min"], 2)))
        lines.append("    max:   " + str(round(stats["max"], 2)))
        lines.append("    mean:  " + str(round(stats["mean"], 2)))
        lines.append("    stdev: " + str(round(stats["stdev"], 2)))
    lines.append("")
    lines.append("BIGGEST MOVERS")
    for symbol, change in movers:
        lines.append("  " + symbol + ": " + str(round(change, 1)) + "%")

    duplicates = find_duplicates(points)
    if duplicates:
        lines.append("")
        lines.append("WARNING: " + str(len(duplicates)) + " duplicate observations")

    return "\n".join(lines)


def write_report(points: list[PricePoint], path: str) -> None:
    """Write the report to a file."""
    with open(path, "w") as handle:
        handle.writelines(render_report(points))


